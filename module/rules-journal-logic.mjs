const esc = (s) => String(s ?? "").replace(/[&<>"']/g, c => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" }[c]));
const signed = (n) => (n >= 0 ? `+${n}` : `${n}`);
const table = (head, rows) => `<table><thead><tr>${head.map(h => `<th>${esc(h)}</th>`).join("")}</tr></thead><tbody>${rows.map(r => `<tr>${r.map(c => `<td>${c}</td>`).join("")}</tr>`).join("")}</tbody></table>`;
const list = (items) => `<ul>${items.map(i => `<li>${i}</li>`).join("")}</ul>`;

/** A neutral app state (all abilities 10, nothing bought) with some fields replaced. */
export function baseState(over = {}) {
  return {
    mode: "turm", startAp: 0, earnedAp: 0, abilities: { str: 10, dex: 10, con: 10, int: 10, wis: 10, cha: 10 },
    bought: {}, choices: {}, milestones: {}, selectedSkills: [], selectedProfs: [], customProfs: [], hpRolls: [],
    play: { exhaustion: 0 }, spUsed: 0, layUsed: 0, slotsUsed: {}, armor: { id: "none", shield: false }, feats: [], ...over
  };
}

/** The first earned-AP value (0..limit) at which `pick(derived)` reaches each new value. */
export function thresholds(pick, limit = 600) {
  const out = [];
  let last;
  for (let e = 0; e <= limit; e++) {
    const v = pick(derived(baseState({ earnedAp: e })));
    if (v !== last) { out.push({ earned: e, value: v }); last = v; }
  }
  return out;
}

