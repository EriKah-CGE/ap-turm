/** Cost ladder text: "10, 20, 40, then ×2" / "30 (once)". */
export function ladderText(item) {
  const first = item.costs.map(String).join(", ");
  if (isMaxed(item, item.costs.length) && !item.maxRanks) return `${first} (once)`;
  const mult = item.mult !== undefined ? item.mult : 2;
  return `${first}, then ×${mult}`;
}

/** Max ranks text: "1", "5" (custom), "unlimited". */
export function maxRanksText(item) {
  if (item.maxRanks) return String(item.maxRanks);
  return isMaxed(item, 1) ? "1" : "unlimited";
}

export function shopPage(shop = SHOP_DATA) {
  let html = `<p>Costs in AP per rank. Beyond the listed ladder every further rank costs the last price × the multiplier.
Prerequisites must be bought first; selling a prerequisite also sells what depends on it. ★ = custom entry of this world.</p>`;
  for (const [cat, entries] of Object.entries(shop)) {
    html += `<h2>${esc(cat)}</h2>`;
    html += table(["Entry", "Costs", "Max ranks", "Requires", "Choice at purchase"], entries.map(it => {
      const custom = it.custom ? customEntry(it.id) : null;
      const req = prereqList(it.id).map(r => esc(findShopItem(r)?.name ?? r)).join(", ") || "—";
      const choice = custom ? (custom.choice && custom.choice !== "none" ? esc(CHOICE_TYPES[custom.choice] ?? custom.choice) : "—") : esc(SELECTORS[it.id]?.label ?? "—");
      let name = `${it.custom ? "★ " : ""}<b>${esc(it.name)}</b>`;
      const desc = it.desc || custom?.desc;
      if (desc) name += `<br><small>${esc(desc)}</small>`;
      if (custom?.effects?.length) name += `<br><small>${custom.effects.map(e => esc(effectLabel(e))).join(" · ")}</small>`;
      return [name, esc(ladderText(it)), maxRanksText(it), req, choice];
    }));
  }
  return html;
}

