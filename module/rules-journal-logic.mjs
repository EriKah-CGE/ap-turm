  const def = (kind) => ({ resistances: [], immunities: [], vulnerabilities: [], [kind]: ["feuer"] });
  const mRes = damageMultiplier("feuer", def("resistances"), { mode: "turm" });
  const mImm = damageMultiplier("feuer", def("immunities"), { mode: "turm" });
